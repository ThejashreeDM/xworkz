package com.xworkz.inheritancemodule.fruit;

public class Fruit
{
    public void eat()
    {
        System.out.println("Fruits are to eat");
    }
    public void grow() {
        System.out.println("The fruit is growing on the tree.");
    }

    public void ripen() {
        System.out.println("The fruit is ripening.");
    }

    public void harvest() {
        System.out.println("The fruit is being harvested.");
    }

    public void pack() {
        System.out.println("The fruit is packed for sale.");
    }

    public void sell() {
        System.out.println("The fruit is sold at the market.");
    }
}
