package com.xworkz.inheritancemodule.movie;

public class Movie
{
    public void entertainment()
    {
        System.out.println("Movie provides entertainment");
    }
    public void start() {
        System.out.println("Starting the movie.");
    }

    public void play() {
        System.out.println("Playing the movie.");
    }

    public void pause() {
        System.out.println("Pausing the movie.");
    }

    public void resume() {
        System.out.println("Resuming the movie.");
    }

    public void stop() {
        System.out.println("Stopping the movie.");
    }
}
