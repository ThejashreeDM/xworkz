package com.xworkz.inheritancemodule.season;

public class Season
{
    public void variations()
    {
        System.out.println("Seasons causes variation in environment");
    }
    public void start() {
        System.out.println("The season is starting.");
    }

    public void end() {
        System.out.println("The season is coming to an end.");
    }

    public void changeWeather() {
        System.out.println("The weather is changing according to the season.");
    }

    public void bringFestivities() {
        System.out.println("The season brings various festivities and events.");
    }

    public void affectAgriculture() {
        System.out.println("The season affects the agricultural cycle.");
    }
}
