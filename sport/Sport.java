public class Sport
{
    public void exercise()
    {
        System.out.println("Sport is a form of exercise");
    }
    public void startGame() {
        System.out.println("Starting the sport game.");
    }

    public void play() {
        System.out.println("Playing the sport with rules and strategies.");
    }

    public void score() {
        System.out.println("Scoring points or runs in the sport.");
    }

    public void pauseGame() {
        System.out.println("Pausing the game for a break or interval.");
    }

    public void endGame() {
        System.out.println("Ending the game after the final whistle or point.");
    }
}
