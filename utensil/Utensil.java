package com.xworkz.inheritancemodule.utensil;

public class Utensil
{
    public void store()
    {
        System.out.println("purpose of utensil is to store something");
    }
    public void clean() {
        System.out.println("Cleaning the utensil before use.");
    }

    public void serve() {
        System.out.println("Serving food using the utensil.");
    }

    public void maintain() {
        System.out.println("Maintaining the utensil to avoid wear and tear.");
    }

    public void dispose() {
        System.out.println("Disposing of the utensil if it is no longer usable.");
    }
}
