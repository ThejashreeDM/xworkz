package com.xworkz.inheritancemodule.medicine;

public class Medicine
{
    public void treatDisease()
    {
        System.out.println("Medicines are used to treat diseases");
    }
    public void diagnose() {
        System.out.println("Diagnosing the patient's condition.");
    }

    public void prescribe() {
        System.out.println("Prescribing medicine to the patient.");
    }

    public void treat() {
        System.out.println("Treating the patient with appropriate medicine.");
    }

    public void monitor() {
        System.out.println("Monitoring the patient's progress.");
    }

    public void dispense() {
        System.out.println("Dispensing medicine to the patient.");
    }
}
