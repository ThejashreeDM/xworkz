package com.xworkz.inheritancemodule.vehicle;

public class Vehicle
{
    public void transport()
    {
        System.out.println("Vehicles are used for transport purpose");
    }
    public void startEngine() {
        System.out.println("Starting the vehicle's engine.");
    }

    public void stopEngine() {
        System.out.println("Stopping the vehicle's engine.");
    }

    public void refuel() {
        System.out.println("Refueling the vehicle.");
    }

    public void drive() {
        System.out.println("Driving the vehicle to the destination.");
    }

    public void park() {
        System.out.println("Parking the vehicle safely.");
    }
}
