package com.xworkz.inheritancemodule.hospital;

public class Hospital
{
    public void treat()
    {
        System.out.println("Hospital purpose is to treat");
    }
    public void admitPatient() {
        System.out.println("Admitting a patient to the hospital.");
    }

    public void diagnose() {
        System.out.println("Diagnosing the patient's condition.");
    }

    public void provideTreatment() {
        System.out.println("Providing treatment to the patient.");
    }

    public void dischargePatient() {
        System.out.println("Discharging the patient from the hospital.");
    }

    public void scheduleFollowUp() {
        System.out.println("Scheduling a follow-up appointment.");
    }
}
