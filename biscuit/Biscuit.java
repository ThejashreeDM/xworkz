package com.xworkz.inheritancemodule.biscuit;

public class Biscuit
{
    public void eat()
    {
        System.out.println("Biscuit is a snack");
    }
    public void bake() {
        System.out.println("Baking a biscuit.");
    }

    public void pack() {
        System.out.println("Packing the biscuit.");
    }

    public void addFlavor() {
        System.out.println("Adding flavor to the biscuit.");
    }

    public void checkFreshness() {
        System.out.println("Checking biscuit freshness.");
    }

    public void label() {
        System.out.println("Labeling the biscuit pack.");
    }
}
